import { screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { ApiError } from '@/api/client'
import * as content from '@/api/content'
import * as interviews from '@/api/interviews'
import type { Dashboard, QuestionMeta } from '@/api/types'
import { useAuth } from '@/context/AuthContext'
import { interviewOut, renderApp } from '@/test/utils'
import Dashboard_ from './Dashboard'
import InterviewHistory from './InterviewHistory'
import InterviewSetup from './InterviewSetup'

vi.mock('@/api/content')
vi.mock('@/api/interviews')
vi.mock('@/context/AuthContext', () => ({ useAuth: vi.fn() }))
vi.mock('@/components/dashboard/ScoreTrendChart', () => ({ default: ({ points }: { points: unknown[] }) => <div data-testid="trend-chart">{points.length} points</div> }))
const c = vi.mocked(content)
const iv = vi.mocked(interviews)

const dash = (over: Partial<Dashboard> = {}): Dashboard => ({
  total_interviews: 0, in_progress_count: 0, average_score: null, best_score: null, weakest_subject: null, score_trend: [],
  subject_performance: [], recent_interviews: [], recommendations: [{ title: 'Start your first mock interview', detail: 'Pick a subject.', subject: null }],
  recommendations_source: 'rule_based', is_ai_generated: false, notice: 'Recommendations are generated by simple rules.', ...over,
})

beforeEach(() => {
  vi.resetAllMocks()
  vi.mocked(useAuth).mockReturnValue({ user: { id: 1, email: 'a@example.com', full_name: 'Ayesha Khan', created_at: '2026-01-01T00:00:00', preferences: {} }, status: 'authenticated', signIn: vi.fn(), signUp: vi.fn(), signOut: vi.fn() })
})

describe('Dashboard', () => {
  it('new user: honest empty state, no fabricated numbers', async () => {
    c.getDashboard.mockResolvedValue(dash())
    renderApp(<Dashboard_ />)
    expect(await screen.findByText('Welcome back, Ayesha')).toBeInTheDocument()
    expect(await screen.findByText('Start your first mock interview', { selector: 'h3' })).toBeInTheDocument()
    expect(screen.getAllByText('—').length).toBe(2) // average and best are null, not 0
    expect(screen.queryByTestId('trend-chart')).not.toBeInTheDocument()
  })

  it('renders every figure from the API response', async () => {
    c.getDashboard.mockResolvedValue(dash({
      total_interviews: 3, in_progress_count: 1, average_score: 71.5, best_score: 88, weakest_subject: 'English',
      score_trend: [{ interview_id: 1, subject: 'English', score: 60, completed_at: '2026-11-01T10:00:00' }, { interview_id: 2, subject: 'Islamic Studies', score: 83, completed_at: '2026-11-02T10:00:00' }],
      subject_performance: [{ subject: 'English', sessions_count: 2, avg_score: 60, best_score: 62, last_score: 58 }, { subject: 'Islamic Studies', sessions_count: 1, avg_score: 83, best_score: 83, last_score: 83 }],
      recent_interviews: [interviewOut({ id: 5, subject: 'English', status: 'completed', overall_score: 58 }), interviewOut({ id: 6, subject: 'Islamic Studies', status: 'in_progress' })],
      recommendations: [{ title: 'Strengthen English', detail: 'Your average in English is 60/100.', subject: 'English' }],
    }))
    renderApp(<Dashboard_ />)
    expect(await screen.findByText('71.5')).toBeInTheDocument()
    expect(screen.getByText('88.0')).toBeInTheDocument()
    expect(screen.getByText('Completed interviews').parentElement).toHaveTextContent('3')
    expect(screen.getByText('You have 1 unfinished interview')).toBeInTheDocument()
    expect(await screen.findByTestId('trend-chart')).toHaveTextContent('2 points')
    expect(screen.getByText('Weakest')).toBeInTheDocument()
    expect(screen.getByText('Strengthen English')).toBeInTheDocument()
    // recommendations are labelled as rule-based, never AI
    expect(screen.getByText(/rule-based suggestions .* not ai-generated/i)).toBeInTheDocument()
    // links: completed -> report, in progress -> room
    const links = screen.getAllByRole('link').map((a) => a.getAttribute('href'))
    expect(links).toContain('/interviews/5/results')
    expect(links).toContain('/interviews/6')
  })

  it('shows an error with a working retry', async () => {
    c.getDashboard.mockRejectedValueOnce(new ApiError('Cannot reach the server.', { kind: 'network' })).mockResolvedValue(dash({ total_interviews: 1, average_score: 50, best_score: 50 }))
    renderApp(<Dashboard_ />)
    expect(await screen.findByText("We couldn't load your dashboard")).toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: 'Try again' }))
    expect(await screen.findByText('Completed interviews')).toBeInTheDocument()
  })
})

const meta: QuestionMeta = {
  total: 32, tags: [], notice: 'Sample question bank: unverified study aids.',
  subjects: [
    { subject: 'English', count: 16, difficulties: { easy: 5, medium: 7, hard: 4 }, topics: [{ topic: 'Grammar', count: 6 }, { topic: 'Composition', count: 4 }] },
    { subject: 'Islamic Studies', count: 16, difficulties: { easy: 5, medium: 6, hard: 5 }, topics: [{ topic: 'Seerah', count: 3 }] },
  ],
}

describe('InterviewSetup', () => {
  beforeEach(() => c.getQuestionMeta.mockResolvedValue(meta))
  const open = async () => { renderApp(<InterviewSetup />, { route: '/interviews/new', path: '/interviews/new' }); await screen.findByText('Interview settings') }

  it('lists real subjects and topics from the question metadata', async () => {
    await open()
    const subject = screen.getByLabelText('Subject')
    expect(within(subject).getAllByRole('option').map((o) => o.textContent)).toEqual(['Select a subject…', 'English (16)', 'Islamic Studies (16)'])
    expect(screen.getByLabelText('Topic (optional)')).toBeDisabled()
    await userEvent.selectOptions(subject, 'English')
    expect(screen.getByLabelText('Topic (optional)')).toBeEnabled()
    expect(within(screen.getByLabelText('Topic (optional)')).getAllByRole('option').map((o) => o.textContent)).toEqual(['Any topic', 'Grammar (6)', 'Composition (4)'])
  })

  it('requires a subject and does not call the API without one', async () => {
    await open()
    await userEvent.click(screen.getByRole('button', { name: /start interview/i }))
    expect(await screen.findByText('Choose a subject')).toBeInTheDocument()
    expect(iv.startInterview).not.toHaveBeenCalled()
  })

  it('refuses more questions than the bank has for that choice, with a clear message', async () => {
    await open()
    await userEvent.selectOptions(screen.getByLabelText('Subject'), 'English')
    await userEvent.click(screen.getByText('Hard')) // label: only 4 hard English questions exist
    const n = screen.getByLabelText('Number of questions')
    await userEvent.clear(n)
    await userEvent.type(n, '9')
    await userEvent.click(screen.getByRole('button', { name: /start interview/i }))
    expect(await screen.findByText(/only 4 questions are available/i)).toBeInTheDocument()
    expect(iv.startInterview).not.toHaveBeenCalled()
  })

  it('validates number ranges', async () => {
    await open()
    await userEvent.selectOptions(screen.getByLabelText('Subject'), 'English')
    const n = screen.getByLabelText('Number of questions')
    await userEvent.clear(n); await userEvent.type(n, '25')
    const d = screen.getByLabelText('Duration (minutes)')
    await userEvent.clear(d); await userEvent.type(d, '3')
    await userEvent.click(screen.getByRole('button', { name: /start interview/i }))
    expect(await screen.findByText('Choose 20 questions or fewer')).toBeInTheDocument()
    expect(screen.getByText('Choose at least 5 minutes')).toBeInTheDocument()
    expect(iv.startInterview).not.toHaveBeenCalled()
  })

  it('starts the interview with the chosen settings and opens the room', async () => {
    iv.startInterview.mockResolvedValue({ interview: interviewOut({ id: 42 }), question: { id: 1, subject: 'English', topic: 'Grammar', difficulty: 'easy', text: 'Q?' }, question_number: 1, total_questions: 3, notice: '', introduction_required: false, introduction_prompt: null })
    await open()
    await userEvent.selectOptions(screen.getByLabelText('Subject'), 'English')
    await userEvent.selectOptions(screen.getByLabelText('Topic (optional)'), 'Grammar')
    await userEvent.click(screen.getByText('Practice'))
    const n = screen.getByLabelText('Number of questions')
    await userEvent.clear(n); await userEvent.type(n, '3')
    await userEvent.click(screen.getByRole('button', { name: /start interview/i }))
    await waitFor(() => expect(iv.startInterview).toHaveBeenCalledTimes(1))
    expect(iv.startInterview.mock.calls[0][0]).toEqual({ subject: 'English', difficulty: 'mixed', num_questions: 3, duration_minutes: 30, mode: 'practice', topic: 'Grammar', with_introduction: true })
    await waitFor(() => expect(screen.getByTestId('location')).toHaveTextContent('/interviews/42'))
  })

  it('shows the backend error (400) and stays on the page', async () => {
    iv.startInterview.mockRejectedValue(new ApiError('Only 0 question(s) available for English / Grammar (hard); requested 3.', { kind: 'http', status: 400 }))
    await open()
    await userEvent.selectOptions(screen.getByLabelText('Subject'), 'English')
    await userEvent.click(screen.getByRole('button', { name: /start interview/i }))
    expect(await screen.findByText(/Only 0 question\(s\) available/)).toBeInTheDocument()
    expect(screen.getByTestId('location')).toHaveTextContent('/interviews/new')
  })

  it('is honest that duration and mode are not enforced by the server', async () => {
    await open()
    expect(screen.getByText(/the server does not stop the interview when time runs out/i)).toBeInTheDocument()
  })

  it('shows an error state with retry when the question bank cannot load', async () => {
    c.getQuestionMeta.mockRejectedValueOnce(new ApiError('Cannot reach the server.', { kind: 'network' })).mockResolvedValue(meta)
    renderApp(<InterviewSetup />)
    await userEvent.click(await screen.findByRole('button', { name: 'Try again' }))
    expect(await screen.findByText('Interview settings')).toBeInTheDocument()
  })
})

describe('InterviewHistory', () => {
  const rows = (n: number, start = 1) => Array.from({ length: n }, (_, i) => interviewOut({ id: start + i, subject: `Subject ${start + i}`, status: i % 2 ? 'in_progress' : 'completed', overall_score: i % 2 ? null : 64.5 }))

  it('empty state for a new user', async () => {
    iv.listHistory.mockResolvedValue([])
    renderApp(<InterviewHistory />)
    expect(await screen.findByText('No interviews yet')).toBeInTheDocument()
  })

  it('lists interviews with report / resume actions and scores only for completed ones', async () => {
    iv.listHistory.mockResolvedValue(rows(2))
    renderApp(<InterviewHistory />)
    const table = await screen.findByRole('table')
    expect(within(table).getByText('64.5')).toBeInTheDocument()
    const report = within(table).getByRole('link', { name: /view report/i })
    const resume = within(table).getByRole('link', { name: /resume/i })
    expect(report).toHaveAttribute('href', '/interviews/1/results')
    expect(resume).toHaveAttribute('href', '/interviews/2')
    expect(within(table).getByText('Completed')).toBeInTheDocument()
    expect(within(table).getByText('In progress')).toBeInTheDocument()
  })

  it('paginates with limit/offset and stops when a page is not full', async () => {
    iv.listHistory.mockImplementation(async ({ offset = 0 } = {}) => (offset === 0 ? rows(10) : rows(3, 11)))
    renderApp(<InterviewHistory />)
    await screen.findByRole('table')
    expect(iv.listHistory).toHaveBeenCalledWith({ limit: 10, offset: 0 })
    expect(screen.getByRole('button', { name: /previous/i })).toBeDisabled()
    await userEvent.click(screen.getByRole('button', { name: /next/i }))
    await waitFor(() => expect(iv.listHistory).toHaveBeenCalledWith({ limit: 10, offset: 10 }))
    await screen.findByText('Page 2')
    await waitFor(() => expect(screen.getByRole('button', { name: /next/i })).toBeDisabled())
  })

  it('shows an error with retry', async () => {
    iv.listHistory.mockRejectedValueOnce(new ApiError('Cannot reach the server.', { kind: 'network' })).mockResolvedValue(rows(1))
    renderApp(<InterviewHistory />)
    await userEvent.click(await screen.findByRole('button', { name: 'Try again' }))
    expect(await screen.findByRole('table')).toBeInTheDocument()
  })
})
