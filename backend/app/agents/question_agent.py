"""Question Agent: chooses interview questions from the curated bank (Phase 5 retrieval).

Questions are retrieved, not generated by the LLM, so every question has a reference answer, concepts and
evaluation criteria to ground the evaluation. Follow-up questions are the Evaluation/Conductor agents' job.
"""

from sqlalchemy.orm import Session

from app.models.question import Question
from app.rag import RetrievalQuery, get_retriever, select_questions


class QuestionAgent:
    def __init__(self, db: Session):
        self.db = db

    def candidates(self, subject: str, difficulty: str, topic: str | None) -> list[Question]:
        result = get_retriever(self.db).search(
            RetrievalQuery(
                subject=subject, topic=topic, difficulty=None if difficulty == "mixed" else difficulty, limit=None
            )
        )
        return [sq.question for sq in result.items]

    @staticmethod
    def pick(candidates: list[Question], n: int, recently_seen_ids: list[int], mixed: bool) -> list[Question]:
        return select_questions(candidates, n, recently_seen_ids=recently_seen_ids, mixed_difficulty=mixed)
