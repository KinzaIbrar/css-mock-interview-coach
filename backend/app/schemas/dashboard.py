from datetime import datetime

from pydantic import BaseModel

from app.schemas.interview import InterviewOut


class SubjectPerformance(BaseModel):
    subject: str
    sessions_count: int
    avg_score: float
    best_score: float
    last_score: float


class TrendPoint(BaseModel):
    interview_id: int
    subject: str
    score: float
    completed_at: datetime


class Recommendation(BaseModel):
    title: str
    detail: str
    subject: str | None = None


class DashboardOut(BaseModel):
    total_interviews: int  # completed sessions
    in_progress_count: int
    average_score: float | None
    best_score: float | None
    weakest_subject: str | None
    score_trend: list[TrendPoint]
    subject_performance: list[SubjectPerformance]
    recent_interviews: list[InterviewOut]
    recommendations: list[Recommendation]
    recommendations_source: str = "rule_based"
    is_ai_generated: bool = False
    notice: str = "Recommendations are generated by simple rules from your saved results, not by an AI model."


class ProgressOut(BaseModel):
    total_completed: int
    overall_average: float | None
    subjects: list[SubjectPerformance]
    trend: list[TrendPoint]
